/**
 * Get all Google Ads metrics
 */
export function getGoogleAdsMetrics(): GoogleAdsMetricDefinition[] {
  return GOOGLE_ADS_METRIC_CATALOG;
}

/**
 * Get metric definition by key
 */
export function getGoogleAdsMetricByKey(
  key: string
): GoogleAdsMetricDefinition | undefined {
  return GOOGLE_ADS_METRIC_CATALOG.find((m) => m.key === key);
}

/**
 * Get metrics by category
 */
export function getGoogleAdsMetricsByCategory(
  category: GoogleAdsMetricCategory
): GoogleAdsMetricDefinition[] {
  return GOOGLE_ADS_METRIC_CATALOG.filter((m) => m.category === category);
}

/**
 * Get API-only metrics (optionally filtered by keys)
 */
export function getGoogleAdsApiMetrics(
  keys?: string[]
): GoogleAdsMetricDefinition[] {
  const apiMetrics = GOOGLE_ADS_METRIC_CATALOG.filter(
    (m) => m.type === "api"
  );
  if (!keys || keys.length === 0) return apiMetrics;
  return apiMetrics.filter((m) => keys.includes(m.key));
}

/**
 * Get calculated-only metrics (optionally filtered by keys)
 */
export function getGoogleAdsCalculatedMetrics(
  keys?: string[]
): GoogleAdsMetricDefinition[] {
  const calcMetrics = GOOGLE_ADS_METRIC_CATALOG.filter(
    (m) => m.type === "calculated"
  );
  if (!keys || keys.length === 0) return calcMetrics;
  return calcMetrics.filter((m) => keys.includes(m.key));
}

/**
 * Convert metric keys to GAQL API fields.
 * For calculated metrics, includes the API fields of their dependencies.
 */
export function googleAdsMetricKeysToApiFields(keys: string[]): string[] {
  const apiFields = new Set<string>();

  for (const key of keys) {
    const metric = getGoogleAdsMetricByKey(key);
    if (!metric) continue;

    if (metric.type === "api" && metric.apiField) {
      apiFields.add(metric.apiField);
    } else if (metric.type === "calculated" && metric.dependencies) {
      // For calculated metrics, resolve the dependencies to their API fields
      for (const depKey of metric.dependencies) {
        const depMetric = getGoogleAdsMetricByKey(depKey);
        if (depMetric?.type === "api" && depMetric.apiField) {
          apiFields.add(depMetric.apiField);
        }
      }
    }
  }

  return Array.from(apiFields);
}

/**
 * Get metric definition by API field
 */
export function getGoogleAdsMetricByApiField(
  apiField: string
): GoogleAdsMetricDefinition | undefined {
  return GOOGLE_ADS_METRIC_CATALOG.find(
    (m) => m.apiField === apiField && m.type === "api"
  );
}

/**
 * Get all metric categories present in the catalog
 */
export function getGoogleAdsMetricCategories(): GoogleAdsMetricCategory[] {
  return [...new Set(GOOGLE_ADS_METRIC_CATALOG.map((m) => m.category))];
}

/**
 * Get dependencies for calculated metrics
 */
export function getGoogleAdsMetricDependencies(keys: string[]): string[] {
  const dependencies = new Set<string>();

  for (const key of keys) {
    const metric = getGoogleAdsMetricByKey(key);
    if (metric?.type === "calculated" && metric.dependencies) {
      for (const dep of metric.dependencies) {
        dependencies.add(dep);
      }
    }
  }

  return Array.from(dependencies);
}

/**
 * Get count of metrics by category
 */
export function getGoogleAdsMetricCountByCategory(): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const metric of GOOGLE_ADS_METRIC_CATALOG) {
    counts[metric.category] = (counts[metric.category] || 0) + 1;
  }
  return counts;
}

/**
 * Get metrics compatible with a specific resource type
 */
export function getGoogleAdsMetricsForResource(
  resource: GoogleAdsResourceType
): GoogleAdsMetricDefinition[] {
  return GOOGLE_ADS_METRIC_CATALOG.filter(
    (m) =>
      !m.compatibleResources || m.compatibleResources.includes(resource)
  );
}

